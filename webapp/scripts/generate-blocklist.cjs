/**
 * Generates lib/disposable-domains.ts from the GitHub blocklist.
 * Run once: node scripts/generate-blocklist.cjs
 */
const https = require("https");
const fs = require("fs");
const path = require("path");

const URL =
  "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/master/disposable_email_blocklist.conf";

console.log("Fetching blocklist...");

https.get(URL, (res) => {
  let data = "";
  res.on("data", (chunk) => (data += chunk));
  res.on("end", () => {
    const domains = data
      .split(/\s+/)
      .map((d) => d.trim().toLowerCase())
      .filter((d) => d.length > 0 && d.includes("."));

    console.log(`Got ${domains.length} domains.`);

    const out = `// Auto-generated by scripts/generate-blocklist.cjs
// Source: https://github.com/disposable-email-domains/disposable-email-domains
// Run "node scripts/generate-blocklist.cjs" to refresh.
const DISPOSABLE_DOMAINS = new Set<string>(${JSON.stringify(domains, null, 0)});

export function isDisposableEmail(email: string): boolean {
  const domain = email.split("@")[1]?.toLowerCase();
  if (!domain) return false;
  return DISPOSABLE_DOMAINS.has(domain);
}
`;

    const outPath = path.join(__dirname, "../lib/disposable-domains.ts");
    fs.writeFileSync(outPath, out);
    console.log(`Written to ${outPath}`);
  });
});
